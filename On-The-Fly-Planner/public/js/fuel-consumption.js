    /**
     * Helper: Linear Interpolation
     */
    lerp: function(x, x0, x1, y0, y1) {
        if (x1 === x0) return y0;
        return y0 + (x - x0) * (y1 - y0) / (x1 - x0);
    },

    /**
     * Get Value from a specific Altitude Table (Used for both Fuel and Mach)
     */
    getRateFromTable: function(table, weight, dragIndex) {
        // 1. Closest Drag Column
        const headers = this.diHeaders;
        const closestDrag = headers.reduce((prev, curr) => 
            Math.abs(curr - dragIndex) < Math.abs(prev - dragIndex) ? curr : prev
        );
        const colIndex = headers.indexOf(closestDrag);

        // 2. Interpolate Weight Rows
        const weightKeys = Object.keys(table).map(Number).sort((a,b) => a - b);
        let wLow = weightKeys[0]; 
        let wHigh = weightKeys[weightKeys.length-1];

        // Bounds check/Find Bracket
        if(weight < wLow) { wHigh = wLow; }
        else if(weight > wHigh) { wLow = wHigh; }
        else {
            for (let i = 0; i < weightKeys.length - 1; i++) {
                if (weight >= weightKeys[i] && weight <= weightKeys[i+1]) {
                    wLow = weightKeys[i];
                    wHigh = weightKeys[i+1];
                    break;
                }
            }
        }

        const valLow = table[wLow][colIndex];
        const valHigh = table[wHigh][colIndex];

        return this.lerp(weight, wLow, wHigh, valLow, valHigh);
    },

    /**
     * GENERIC INTERPOLATOR
     * Handles Altitude Interpolation for any database (Fuel or Mach)
     */
    interpolateValue: function(database, altitude, weight, dragIndex) {
        const altKeys = Object.keys(database).map(Number).sort((a,b) => a - b);
        let altLow = altKeys[0];
        let altHigh = altKeys[altKeys.length-1];

        if (altitude < altLow) altHigh = altLow; 
        else if (altitude > altHigh) altLow = altHigh;
        else {
            for (let i = 0; i < altKeys.length - 1; i++) {
                if (altitude >= altKeys[i] && altitude <= altKeys[i+1]) {
                    altLow = altKeys[i];
                    altHigh = altKeys[i+1];
                    break;
                }
            }
        }

        const valLow = this.getRateFromTable(database[altLow], weight, dragIndex);
        const valHigh = this.getRateFromTable(database[altHigh], weight, dragIndex);

        return this.lerp(altitude, altLow, altHigh, valLow, valHigh);
    },

    // --- PUBLIC FUNCTIONS ---

    calculateLegBurn: function(distanceNM, altitude, weight, dragIndex, profile = 'RANGE') {
        const database = (profile === 'ENDURANCE') ? this.enduranceTables : this.rangeTables;
        let rate = this.interpolateValue(database, altitude, weight, dragIndex);
        if (rate < 1.0) rate = 1.0; 
        return rate * distanceNM;
    },

    calculateCruiseMach: function(altitude, weight, dragIndex, profile = 'RANGE') {
        const database = (profile === 'ENDURANCE') ? this.machEnduranceTables : this.machRangeTables;
        let mach = this.interpolateValue(database, altitude, weight, dragIndex);
        return mach.toFixed(2);
    }
